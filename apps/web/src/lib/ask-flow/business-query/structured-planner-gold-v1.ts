import type {
  BusinessEntityId,
  BusinessQueryFilterOperator,
  BusinessQueryOperation,
  BusinessQueryScalar,
} from "./types";
import type { PlannerLanguage } from "./structured-planner";

export type GoldCategory =
  "informal_en" | "roman_ur" | "ur" | "mixed" | "typo_adversarial";

export interface StructuredPlannerGoldCase {
  readonly id: string;
  readonly category: GoldCategory;
  readonly message: string;
  readonly language: PlannerLanguage;
  readonly reviewed: true;
  readonly expected:
    | {
        readonly outcome: "query";
        readonly operation: BusinessQueryOperation;
        readonly entity: BusinessEntityId;
        readonly filters: readonly {
          readonly field: string;
          readonly operator: BusinessQueryFilterOperator;
          readonly value: BusinessQueryScalar;
        }[];
        readonly sort: readonly {
          readonly field: string;
          readonly direction: "asc";
        }[];
      }
    | { readonly outcome: "clarify" | "unsupported" | "denied" };
}

type Filter = Extract<
  StructuredPlannerGoldCase["expected"],
  { readonly outcome: "query" }
>["filters"][number];

const f = (
  field: string,
  operator: BusinessQueryFilterOperator,
  value: BusinessQueryScalar,
): Filter => ({ field, operator, value });

const q = (
  id: string,
  category: GoldCategory,
  language: PlannerLanguage,
  message: string,
  operation: BusinessQueryOperation,
  entity: BusinessEntityId,
  filters: readonly Filter[] = [],
  sort: readonly { readonly field: string; readonly direction: "asc" }[] = [],
): StructuredPlannerGoldCase => ({
  id,
  category,
  language,
  message,
  reviewed: true,
  expected: { outcome: "query", operation, entity, filters, sort },
});

const nonQuery = (
  id: string,
  category: GoldCategory,
  language: PlannerLanguage,
  message: string,
  outcome: "clarify" | "unsupported" | "denied",
): StructuredPlannerGoldCase => ({
  id,
  category,
  language,
  message,
  reviewed: true,
  expected: { outcome },
});

